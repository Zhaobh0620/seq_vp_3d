"""E99 (C5, throughput-v17): the fused cubic B-spline sample on CUDA, bit for bit TorchSpline's torch path.

One Triton kernel (spline_fused_kernels.py, generated by scripts/gen_spline_fused.py) evaluates per query point the
basis exactly as cubic_basis does, the 64 coefficient loads, the products ((C*z)*y)*x and torch 2.5.1's CUDA
reduction tree for (n,4,4,4).sum(dim=(1,2,3)); compiled with enable_fp_fusion=False. The reduction tree is torch's,
so the runtime check below guards the equality on every grid (a torch upgrade that changed the tree would be caught
and switch the kernel off): until a grid is verified, TorchSpline computes the torch result as before and, on an
informative call (enough query points strictly inside spline spans on all three axes, so that the basis and the
products are exercised away from the knots), also runs this kernel and compares value and gradient bit for bit.
A match verifies the grid; a mismatch or any failure switches the kernel off for the run (recorded); the torch
result is used in every case until then.
"""
import torch
import triton

from . import spline_fused_kernels as K

POLICY = "fused-spline-torch-tree-v1"
BLOCK, WARPS = 128, 4
INSIDE_MIN = 10_000


def new_record():
    return dict(policy=POLICY, calls=0, compared=0, verified=[], mismatches=0, errors=0, disabled=False,
                unsupported=0)


class FusedSpline:
    """The kernel's constants for one TorchSpline (knots, coefficients) and the run's shared record."""

    def __init__(self, knots, coefficients, grid_id, record):
        self.record, self.grid_id = record, grid_id
        tz, ty, tx = knots
        c = coefficients
        self.supported = bool(c.is_cuda and c.dtype == torch.float64 and c.is_contiguous() and c.dim() == 3
                              and all(t.is_cuda and t.dtype == torch.float64 and t.is_contiguous() and t.dim() == 1
                                      for t in knots)
                              and c.numel() < 2**31 and max(t.numel() for t in knots) < 2**31)
        if not self.supported:
            record["unsupported"] += 1
        self.knots, self.c = (tz, ty, tx), c
        # upper-bound search over len(t) knots: bit_length(len) steps suffice; extra steps are no-ops (lo == hi), so one
        # value (9: up to 511 knots) serves every grid of the usual sizes with a single compiled specialization
        self.nstep = max(9, max(int(t.numel()).bit_length() for t in knots))

    def usable(self, flat):
        return (self.supported and not self.record["disabled"] and flat.is_cuda and flat.dtype == torch.float64
                and flat.is_contiguous() and 3*flat.shape[0] < 2**31)

    def verified(self):
        return self.grid_id in self.record["verified"]

    def chunk(self, flat, start, end, value, gradient):
        """Points [start, end) of flat (n, 3) into value[start:end], gradient[start:end] (absolute offsets)."""
        tz, ty, tx = self.knots
        nz, ny, nx = self.c.shape
        K.spline_fused_kernel[(triton.cdiv(end-start, BLOCK),)](
            flat, self.c, tz, ty, tx, value, gradient, start, end, ny, nx, tz.numel(), ty.numel(), tx.numel(),
            nz-1, ny-1, nx-1, NSTEP=self.nstep, BLOCK=BLOCK, num_warps=WARPS, enable_fp_fusion=False)

    def compare(self, flat, value, gradient, inside, chunk_size):
        """The verification on an unverified grid: the torch result (value, gradient) against the kernel's, bit for
        bit, when `inside` (count of points strictly inside spans on all axes, a device tensor) is large enough."""
        n = flat.shape[0]
        if int(inside) < min(INSIDE_MIN, max(1, n//2)):
            return                                            # not informative: compared later
        result = None
        try:
            # NaN-filled (review E99): torch.empty_like may hand back the torch path's just-freed blocks of the same
            # size, whose stale contents equal the reference; a kernel that missed some outputs would then pass
            v, g = torch.full_like(value, float("nan")), torch.full_like(gradient, float("nan"))
            for start in range(0, n, chunk_size):
                self.chunk(flat, start, min(start+chunk_size, n), v, g)
            result = bool(torch.equal(v.view(torch.int64), value.view(torch.int64))
                          and torch.equal(g.view(torch.int64), gradient.view(torch.int64)))
        except Exception:
            pass
        v = g = None
        if result is None:
            self.record["errors"] += 1
            self.record["disabled"] = True
            return
        self.record["compared"] += 1
        if not result:
            self.record["mismatches"] += 1
            self.record["disabled"] = True
            return
        self.record["verified"].append(self.grid_id)


def inside_count(x, t, indices):
    """Points with x strictly between t[span] and t[span+1] (span = indices[:, 3]); a device bool tensor."""
    span = indices[:, 3]
    return (x != t[span]) & (x != t[span+1])


def prewarm(device="cuda"):
    """Compile the kernel outside a task clock (one specialization serves every grid with at most 511 knots per axis:
    integers are not specialized and NSTEP is 9)."""
    t = torch.arange(-3., 12., dtype=torch.float64, device=device)
    t[:4] = 0.; t[-4:] = 8.
    c = torch.zeros((11, 11, 11), dtype=torch.float64, device=device)
    rec = new_record()
    f = FusedSpline((t, t, t), c, "prewarm", rec)
    p = torch.full((5, 3), 1., dtype=torch.float64, device=device)
    v, g = torch.empty(5, dtype=torch.float64, device=device), torch.empty((5, 3), dtype=torch.float64, device=device)
    f.chunk(p, 0, 5, v, g)
    torch.cuda.synchronize()

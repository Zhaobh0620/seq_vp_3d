"""Generate jd_curl/three_d/backends/triton_screen_prefilter_kernels.py (E93, witness-screen prefilter).

One cell per lane: load the 8 vertex values of u, form the Q1 edge differences ue = (u_b - u_a)*ih_j,
and for each closed27 point build F = I + grad u in the exact edge-difference form and J = F row 0
dotted with the cyclic cross product of rows 1 and 2 (the legacy evaluation shape). Per cell the kernel
writes jmin = min over the 27 points of J (-inf if any J is nonfinite) and the a-priori bound e of
docs/04 §E93 such that |J_legacy - J_fast| <= e at every point, where J_legacy is the torch einsum path
of witness_screen.screen (any summation order, with or without FMA). Only the inequality is used:
jmin - e > delta proves that the legacy screen finds no value <= delta in that cell.
Usage: python scripts/gen_triton_screen_prefilter.py
"""
from itertools import product
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT/'jd_curl/three_d/backends/triton_screen_prefilter_kernels.py'
# vertex index a = 4z + 2y + x (VERTICES order); edge along axis j between bit-0 and bit-1 vertices
EDGES = {j: [(a, a | (1 << j)) for a in range(8) if not a & (1 << j)] for j in range(3)}


def weight(a, j, point):
    """Bilinear weight of the edge starting at vertex a (derivative along j) at a reference point."""
    w = 1.
    for k in range(3):
        if k != j:
            bit = (a >> k) & 1
            w *= point[k] if bit else 1-point[k]
    return w


def lines():
    L = ['"""GENERATED by scripts/gen_triton_screen_prefilter.py (E93). Do not edit by hand.',
         '',
         'k[0:3] = 1/hx, 1/hy, 1/hz (the same doubles as the closed27 operator); k[3] = cA, k[4] = cAo,',
         'k[5] = 1+gamma_3, k[6] = 1/(1-u) rounded up, k[7] = 12*gamma_5, k[8] = 2u, k[9] = safety, k[10] = tiny.',
         '"""',
         'import triton',
         'import triton.language as tl',
         '',
         '',
         '@triton.jit(do_not_specialize=["ncell", "ny", "nx", "cy", "cx"])',
         'def screen_prefilter_kernel(u_ptr, k_ptr, jmin_ptr, e_ptr, ncell, ny, nx, cy, cx, BLOCK: tl.constexpr):',
         '    pid = tl.program_id(0)',
         '    c = (pid*BLOCK+tl.arange(0, BLOCK)).to(tl.int64)',
         '    m = c < ncell',
         '    x0 = c % cx',
         '    y0 = (c//cx) % cy',
         '    z0 = c//(cx*cy)',
         '    base = (z0*ny+y0)*nx+x0',
         '    s = ny*nx',
         '    ih0 = tl.load(k_ptr+0)',
         '    ih1 = tl.load(k_ptr+1)',
         '    ih2 = tl.load(k_ptr+2)',
         '    cA = tl.load(k_ptr+3)',
         '    cAo = tl.load(k_ptr+4)',
         '    g3p = tl.load(k_ptr+5)',
         '    inv1mu = tl.load(k_ptr+6)',
         '    c12 = tl.load(k_ptr+7)',
         '    two_u = tl.load(k_ptr+8)',
         '    safety = tl.load(k_ptr+9)',
         '    tiny = tl.load(k_ptr+10)',
         '    inf = float("inf")',
         '    jmin = tl.full((BLOCK,), inf, tl.float64)',
         '    allfin = m']
    offsets = {a: f'base+{(a >> 2) & 1}*s+{(a >> 1) & 1}*nx+{a & 1}' for a in range(8)}
    for a in range(8):
        for r in range(3):
            L.append(f'    u{a}_{r} = tl.load(u_ptr+({offsets[a]})*3+{r}, mask=m, other=0.)')
    # umax = max |u| over the 8 vertices and 3 components (exact).
    absu = [f'tl.abs(u{a}_{r})' for a in range(8) for r in range(3)]
    L.append(f'    umax = {absu[0]}')
    for t in absu[1:]:
        L.append(f'    umax = tl.maximum(umax, {t})')
    for j in range(3):
        for e, (a, b) in enumerate(EDGES[j]):
            for r in range(3):
                L.append(f'    ue{j}{e}{r} = (u{b}_{r}-u{a}_{r})*ih{j}')
    # mue = max |ue| over the 36 edge differences (exact max of the computed values).
    ues = [f'tl.abs(ue{j}{e}{r})' for j in range(3) for e in range(4) for r in range(3)]
    L.append(f'    mue = {ues[0]}')
    for t in ues[1:]:
        L.append(f'    mue = tl.maximum(mue, {t})')
    for iz, iy, ix in product(range(3), repeat=3):
        point = (ix/2, iy/2, iz/2)
        p = 9*iz+3*iy+ix
        L.append(f'    # point {p}: (x, y, z) = {point}')
        for r in range(3):
            for j in range(3):
                terms = []
                for e, (a, b) in enumerate(EDGES[j]):
                    w = weight(a, j, point)
                    if w == 0.:
                        continue
                    terms.append(f'ue{j}{e}{r}' if w == 1. else f'{w!r}*ue{j}{e}{r}')
                expr = '+'.join(terms)
                if r == j:
                    expr = f'1.+({expr})'
                L.append(f'    F{r}{j} = {expr}')
        # row 0 of the cofactor: cyclic cross product of rows 1 and 2 (the legacy evaluation shape)
        L.append('    A0 = F11*F22-F12*F21')
        L.append('    A1 = F12*F20-F10*F22')
        L.append('    A2 = F10*F21-F11*F20')
        L.append('    J = F00*A0+F01*A1+F02*A2')
        L.append('    fin = (J == J) & (tl.abs(J) < inf)')
        L.append('    allfin = allfin & fin')
        L.append('    jmin = tl.minimum(jmin, tl.where(fin, J, -inf))')
    L += ['    # E93 bound (docs/04 §E93): B bounds |F| of the exact, legacy and fast evaluations;',
          '    # e = 12 gamma_5 B^3 + 18 (A + 2u B) B^2 with A = (gamma_8 + gamma_5) Dsum umax.',
          '    Ao = cAo*umax',
          '    A = cA*umax',
          '    B = (1.+mue*g3p+Ao)*inv1mu',
          '    B2 = B*B',
          '    bound = (c12*B2*B+18.*(A+two_u*B)*B2)*safety+tiny',
          '    jmin = tl.where(allfin, jmin, -inf)',
          '    tl.store(jmin_ptr+c, jmin, mask=m)',
          '    tl.store(e_ptr+c, bound, mask=m)',
          '']
    return L


def main():
    OUT.write_text('\n'.join(lines()))
    print(OUT)


if __name__ == '__main__':
    main()

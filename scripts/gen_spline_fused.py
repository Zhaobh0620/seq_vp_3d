def basis_ops(ax):
    """(dst, op, a, b) for one axis. Knots t[span+j] are named <ax>_tm<|j|> (j < 0) / <ax>_tp<j>; X is the query."""
    k = lambda j: f'{ax}_t{"m" if j < 0 else "p"}{abs(j)}'
    o = []
    add = lambda d, op, a, b: o.append((f'{ax}_{d}', op, a, b))
    X = f'{ax}_X'
    add('r1', 'sub', k(1), X); add('r2', 'sub', k(2), X); add('r3', 'sub', k(3), X)
    add('l1', 'sub', X, k(0)); add('l2', 'sub', X, k(-1)); add('l3', 'sub', X, k(-2))
    # degree 1 (basis[:, 0] = 1.0)
    add('s1', 'add', f'{ax}_r1', f'{ax}_l1'); add('t1', 'div', 'ONE', f'{ax}_s1')
    add('m1', 'mul', f'{ax}_r1', f'{ax}_t1'); add('v0', 'add', 'ZERO', f'{ax}_m1'); add('v1', 'mul', f'{ax}_l1', f'{ax}_t1')
    # degree 2
    add('s2', 'add', f'{ax}_r1', f'{ax}_l2'); add('t2', 'div', f'{ax}_v0', f'{ax}_s2')
    add('m2', 'mul', f'{ax}_r1', f'{ax}_t2'); add('w0', 'add', 'ZERO', f'{ax}_m2'); add('sv2', 'mul', f'{ax}_l2', f'{ax}_t2')
    add('s3', 'add', f'{ax}_r2', f'{ax}_l1'); add('t3', 'div', f'{ax}_v1', f'{ax}_s3')
    add('m3', 'mul', f'{ax}_r2', f'{ax}_t3'); add('w1', 'add', f'{ax}_sv2', f'{ax}_m3'); add('w2', 'mul', f'{ax}_l1', f'{ax}_t3')
    # degree 3
    add('s4', 'add', f'{ax}_r1', f'{ax}_l3'); add('t4', 'div', f'{ax}_w0', f'{ax}_s4')
    add('m4', 'mul', f'{ax}_r1', f'{ax}_t4'); add('B0', 'add', 'ZERO', f'{ax}_m4'); add('sv4', 'mul', f'{ax}_l3', f'{ax}_t4')
    add('s5', 'add', f'{ax}_r2', f'{ax}_l2'); add('t5', 'div', f'{ax}_w1', f'{ax}_s5')
    add('m5', 'mul', f'{ax}_r2', f'{ax}_t5'); add('B1', 'add', f'{ax}_sv4', f'{ax}_m5'); add('sv5', 'mul', f'{ax}_l2', f'{ax}_t5')
    add('s6', 'add', f'{ax}_r3', f'{ax}_l1'); add('t6', 'div', f'{ax}_w2', f'{ax}_s6')
    add('m6', 'mul', f'{ax}_r3', f'{ax}_t6'); add('B2', 'add', f'{ax}_sv5', f'{ax}_m6'); add('B3', 'mul', f'{ax}_l1', f'{ax}_t6')
    # derivative: a_j = t[span+j] - t[span-3+j], b_j = t[span+1+j] - t[span-2+j], where(!= 0, ., 1)
    for j in range(4):
        add(f'a{j}', 'sub', k(j), k(j-3)); add(f'A{j}', 'nz1', f'{ax}_a{j}', None)
        add(f'b{j}', 'sub', k(j+1), k(j-2)); add(f'Bd{j}', 'nz1', f'{ax}_b{j}', None)
    z1 = ['ZERO', f'{ax}_w0', f'{ax}_w1', f'{ax}_w2']; z2 = [f'{ax}_w0', f'{ax}_w1', f'{ax}_w2', 'ZERO']
    for j in range(4):
        add(f'e{j}', 'mul', 'THREE', z1[j]); add(f'f{j}', 'div', f'{ax}_e{j}', f'{ax}_A{j}')
        add(f'g{j}', 'mul', 'THREE', z2[j]); add(f'h{j}', 'div', f'{ax}_g{j}', f'{ax}_Bd{j}')
        add(f'D{j}', 'sub', f'{ax}_f{j}', f'{ax}_h{j}')
    return o


def contraction_ops():
    """Products and the reduction tree. C<a><b><c> are coefficient loads. Returns (ops, [value, gx, gy, gz])."""
    o = []
    mul = lambda d, a, b: o.append((d, 'mul', a, b))
    add = lambda d, a, b: o.append((d, 'add', a, b))
    names = ('V', 'GX', 'GY', 'GZ')
    for ap in range(2):
        R = {n: [] for n in names}
        for b in range(4):
            pairs = {n: [] for n in names}
            for c in range(4):
                for a in (ap, ap+2):
                    C = f'C{a}{b}{c}'; s = f'{a}{b}{c}'
                    mul(f'cz{s}', C, f'z_B{a}'); mul(f'czy{s}', f'cz{s}', f'y_B{b}')
                    mul(f'PV{s}', f'czy{s}', f'x_B{c}'); mul(f'PGX{s}', f'czy{s}', f'x_D{c}')
                    mul(f'czdy{s}', f'cz{s}', f'y_D{b}'); mul(f'PGY{s}', f'czdy{s}', f'x_B{c}')
                    mul(f'cdz{s}', C, f'z_D{a}'); mul(f'cdzy{s}', f'cdz{s}', f'y_B{b}'); mul(f'PGZ{s}', f'cdzy{s}', f'x_B{c}')
                for n, p in zip(names, ('PV', 'PGX', 'PGY', 'PGZ')):
                    leaf = f'L{n}{ap}{b}{c}'
                    add(leaf, f'{p}{ap}{b}{c}', f'{p}{ap+2}{b}{c}')        # s_l = P[l] + P[l+32]
                    pairs[n].append(leaf)
            for n in names:
                lv = pairs[n]
                add(f'p01{n}{ap}{b}', lv[0], lv[1]); add(f'p23{n}{ap}{b}', lv[2], lv[3])
                add(f'R{n}{ap}{b}', f'p01{n}{ap}{b}', f'p23{n}{ap}{b}'); R[n].append(f'R{n}{ap}{b}')
        for n in names:
            r = R[n]
            add(f'h01{n}{ap}', r[0], r[1]); add(f'h23{n}{ap}', r[2], r[3]); add(f'Q{n}{ap}', f'h01{n}{ap}', f'h23{n}{ap}')
    for n in names:
        add(f'T{n}', f'Q{n}0', f'Q{n}1'); add(f'OUT{n}', f'T{n}', 'ZERO')
    return o, [f'OUT{n}' for n in names]


def source(fp32=False):
    """fp32 (T90, S30-G5 draft): the same operation list on float32 values -- the float64 points are cast to float32 on
    load, the knots and coefficients are float32 arrays, the outputs float32. A screening sampler, never bit-identical to
    the float64 path."""
    C = '.to(tl.float32)' if fp32 else ''
    L = [HEADER_F32 if fp32 else HEADER, '\n']
    w = L.append
    w('@triton.jit(do_not_specialize=["start", "stop", "NY", "NX", "LTZ", "LTY", "LTX", "NZM1", "NYM1", "NXM1"])\n'
      + ('def spline_fused_f32_kernel(' if fp32 else 'def spline_fused_kernel(') + 'p_ptr, c_ptr, tz_ptr, ty_ptr, tx_ptr, val_ptr, grad_ptr, start, stop,\n'
      '                        NY, NX, LTZ, LTY, LTX, NZM1, NYM1, NXM1, NSTEP: tl.constexpr, BLOCK: tl.constexpr):\n')
    w('    offs = start + tl.program_id(0)*BLOCK + tl.arange(0, BLOCK)\n    m = offs < stop\n')
    w('    ZERO = 0.0\n    ONE = 1.0\n    THREE = 3.0\n')
    w(f'    z_X = tl.load(p_ptr + offs*3 + 2, mask=m, other=0.0){C}\n')
    w(f'    y_X = tl.load(p_ptr + offs*3 + 1, mask=m, other=0.0){C}\n')
    w(f'    x_X = tl.load(p_ptr + offs*3 + 0, mask=m, other=0.0){C}\n')
    for ax, LT, NM1 in (('z', 'LTZ', 'NZM1'), ('y', 'LTY', 'NYM1'), ('x', 'LTX', 'NXM1')):
        t = f't{ax}_ptr'
        w(f'    lo = tl.zeros([BLOCK], dtype=tl.int32)\n    hi = lo + {LT}\n')
        w(f'    for _ in tl.static_range(NSTEP):\n        act = lo < hi\n        mid = (lo + hi) // 2\n'
          f'        tm = tl.load({t} + mid, mask=m & act, other=0.0)\n        le = tm <= {ax}_X\n'
          f'        lo = tl.where(act & le, mid + 1, lo)\n        hi = tl.where(act & (~le), mid, hi)\n')
        w(f'    {ax}_span = tl.minimum(tl.maximum(lo - 1, 3), {NM1})\n')      # searchsorted(right=True)-1, clamp
        for j in range(-3, 5):
            nm = f'{ax}_t{"m" if j < 0 else "p"}{abs(j)}'
            w(f'    {nm} = tl.load({t} + {ax}_span + ({j}), mask=m, other=1.0)\n')
        for d, op, a, b in basis_ops(ax):
            if op == 'nz1':
                w(f'    {d} = tl.where({a} != 0.0, {a}, 1.0)\n')
            else:
                w(f'    {d} = {a} {dict(add="+", sub="-", mul="*", div="/")[op]} {b}\n')
    for a in range(4):
        w(f'    oz{a} = ((z_span - 3 + {a})*NY)*NX\n    oy{a} = (y_span - 3 + {a})*NX\n    ox{a} = x_span - 3 + {a}\n')
    ops, outs = contraction_ops()
    loaded = set()
    for d, op, a, b in ops:
        for v in (a, b):
            if v.startswith('C') and v not in loaded:
                loaded.add(v)
                w(f'    {v} = tl.load(c_ptr + oz{v[1]} + oy{v[2]} + ox{v[3]}, mask=m, other=0.0)\n')
        w(f'    {d} = {a} {dict(add="+", mul="*")[op]} {b}\n')
    w(f'    tl.store(val_ptr + offs, {outs[0]}, mask=m)\n')
    w(f'    tl.store(grad_ptr + offs*3 + 0, {outs[1]}, mask=m)\n')
    w(f'    tl.store(grad_ptr + offs*3 + 1, {outs[2]}, mask=m)\n')
    w(f'    tl.store(grad_ptr + offs*3 + 2, {outs[3]}, mask=m)\n')
    return ''.join(L)


def numpy_basis(x, t, n):
    """The basis part of the operation list for one axis in NumPy: (span, basis (m, 4), derivative (m, 4)), to be
    compared with cubic_basis (indices[:, 3] is the span)."""
    import numpy as np
    env = {'ZERO': np.float64(0.), 'ONE': np.float64(1.), 'THREE': np.float64(3.), 'q_X': np.ascontiguousarray(x)}
    span = np.clip(np.searchsorted(t, x, side='right')-1, 3, n-1)
    with np.errstate(all='ignore'):
        for j in range(-3, 5):
            env[f'q_t{"m" if j < 0 else "p"}{abs(j)}'] = t[span+j]
        for d, op, a, b in basis_ops('q'):
            A = env[a]
            if op == 'nz1':
                env[d] = np.where(A != 0, A, 1.)
                continue
            B = env[b]
            env[d] = A+B if op == 'add' else A-B if op == 'sub' else A*B if op == 'mul' else A/B
    return (span, np.stack([env[f'q_B{j}'] for j in range(4)], axis=-1),
            np.stack([env[f'q_D{j}'] for j in range(4)], axis=-1))


def numpy_eval(points, c, knots):
    """The same operation list in NumPy (IEEE float64, no fusion): (value, gradient xyz). points (n, 3) xyz;
    c (nz, ny, nx); knots (tz, ty, tx). Not independent of the kernel (same list): it checks the code generation."""
    import numpy as np
    env = {'ZERO': np.float64(0.), 'ONE': np.float64(1.), 'THREE': np.float64(3.)}
    with np.errstate(all='ignore'):
        for ax, col, t, n in (('z', 2, knots[0], c.shape[0]), ('y', 1, knots[1], c.shape[1]), ('x', 0, knots[2], c.shape[2])):
            x = np.ascontiguousarray(points[:, col]); env[f'{ax}_X'] = x
            span = np.clip(np.searchsorted(t, x, side='right')-1, 3, n-1); env[f'{ax}_span'] = span
            for j in range(-3, 5):
                env[f'{ax}_t{"m" if j < 0 else "p"}{abs(j)}'] = t[span+j]
            for d, op, a, b in basis_ops(ax):
                A = env[a]
                if op == 'nz1':
                    env[d] = np.where(A != 0, A, 1.)
                    continue
                B = env[b]
                env[d] = A+B if op == 'add' else A-B if op == 'sub' else A*B if op == 'mul' else A/B
        nz, ny, nx = c.shape
        flat = c.reshape(-1)
        ops, outs = contraction_ops()
        for d, op, a, b in ops:
            for v in (a, b):
                if v.startswith('C') and v not in env:
                    ia, ib, ic = int(v[1]), int(v[2]), int(v[3])
                    env[v] = flat[((env['z_span']-3+ia)*ny+(env['y_span']-3+ib))*nx+(env['x_span']-3+ic)]
            env[d] = env[a]+env[b] if op == 'add' else env[a]*env[b]
        value, gx, gy, gz = (env[o] for o in outs)
    return value, np.stack((gx, gy, gz), axis=-1)


def main_f32():
    text = source(fp32=True)
    OUT_F32.write_text(text)
    print(OUT_F32, len(text.splitlines())-1, 'lines')


def main():
    text = source()
    OUT.write_text(text)
    print(OUT, len(text.splitlines()), 'lines')
    main_f32()


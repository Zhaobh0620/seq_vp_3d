"""Generate jd_curl/three_d/backends/triton_jd_root_kernels.py (E55b / T66 fused global JD root).

One cell per lane: load the 8 vertex values of u (base) and v (direction), form the Q1
edge differences, and for each closed27 point (index 9*iz+3*iy+ix, reference coordinates
(ix/2, iy/2, iz/2)) build F = I + grad u and V = grad v in the exact edge-difference form,
the cubic coefficients of det(F + tau V) - delta, and its first root in (0, limit] with the
same piecewise-monotone bisection as solvers.global_jd_step / torch_ops.torch_first_roots.
Per-program outputs: min root (s-units, inf if none), count of c0 <= 0 points, nonfinite flag.
Usage: python scripts/gen_triton_jd_root.py
"""
from itertools import product
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT/'jd_curl/three_d/backends/triton_jd_root_kernels.py'
AXES = 'xyz'
# vertex index a = 4z + 2y + x (VERTICES order); edge along axis j between bit-0 and bit-1 vertices
EDGES = {j: [(a, a | (1 << j)) for a in range(8) if not a & (1 << j)] for j in range(3)}


def weight(a, j, point):
    """Bilinear weight of edge starting at vertex a (derivative along j) at reference point."""
    w = 1.
    for k in range(3):
        if k != j:
            bit = (a >> k) & 1
            w *= point[k] if bit else 1-point[k]
    return w


def lines():
    L = ['"""GENERATED by scripts/gen_triton_jd_root.py (E55b, T66 fused). Do not edit by hand.',
         '',
         'k[0:3] = 1/hx, 1/hy, 1/hz; k[3] = delta; k[4:7] = limit, limit**2, limit**3.',
         '"""',
         'import triton',
         'import triton.language as tl',
         '',
         '',
         '@triton.jit',
         'def _first_root(b0, b1, b2, b3, active):',
         '    """Mirror of torch_first_roots for lanes with b0 > 0; inf where no root in (0, 1]."""',
         '    inf = float("inf")',
         '    a = 3.*b3',
         '    b = 2.*b2',
         '    c = b1',
         '    one = tl.full(b0.shape, 1., tl.float64)',
         '    zero = tl.zeros(b0.shape, tl.float64)',
         '    nanv = zero/zero',
         '    linear = a == 0',
         '    r_lin = tl.where(linear & (b != 0), -c/tl.where(b != 0, b, one), nanv)',
         '    disc = b*b-4.*a*c',
         '    sq = tl.sqrt(tl.where(disc >= 0, disc, zero))',
         '    q = -(b+tl.where(b >= 0, sq, -sq))/2.',
         '    r1 = tl.where((~linear) & (disc >= 0) & (a != 0), q/tl.where(a != 0, a, one), nanv)',
         '    r2 = tl.where((~linear) & (disc >= 0) & (q != 0), c/tl.where(q != 0, q, one), nanv)',
         '    r1 = tl.where(linear, r_lin, r1)',
         '    r2 = tl.where(linear, nanv, r2)',
         '    r1 = tl.where((r1 > 0) & (r1 < 1), r1, one)',
         '    r2 = tl.where((r2 > 0) & (r2 < 1), r2, one)',
         '    t1 = tl.minimum(r1, r2)',
         '    t2 = tl.maximum(r1, r2)',
         '    ab0 = tl.abs(b0)',
         '    ab1 = tl.abs(b1)',
         '    ab2 = tl.abs(b2)',
         '    ab3 = tl.abs(b3)',
         '    eps4 = 8.881784197001252e-16',
         '    q1 = b0+t1*(b1+t1*(b2+t1*b3)) <= eps4*(ab0+t1*(ab1+t1*(ab2+t1*ab3)))',
         '    q2 = b0+t2*(b1+t2*(b2+t2*b3)) <= eps4*(ab0+t2*(ab1+t2*(ab2+t2*ab3)))',
         '    q3 = b0+(b1+(b2+b3)) <= 0',
         '    maybe = active & ~(b0 > ab1+ab2+ab3)',
         '    has = maybe & (q1 | q2 | q3)',
         '    hi = tl.where(q1, t1, tl.where(q2, t2, one))',
         '    lo = tl.where(q1, zero, tl.where(q2, t1, t2))',
         '    if tl.sum(has.to(tl.int32), axis=0) > 0:',
         '        for _ in range(50):',
         '            mid = .5*(lo+hi)',
         '            neg = b0+mid*(b1+mid*(b2+mid*b3)) <= 0',
         '            hi = tl.where(neg, mid, hi)',
         '            lo = tl.where(neg, lo, mid)',
         '    return tl.where(has, lo, inf)',
         '',
         '',
         '@triton.jit(do_not_specialize=["ncell", "ny", "nx", "cy", "cx"])',
         'def global_jd_root_kernel(u_ptr, v_ptr, k_ptr, min_ptr, inv_ptr, bad_ptr, ncell, ny, nx, cy, cx,',
         '                          BLOCK: tl.constexpr):',
         '    pid = tl.program_id(0)',
         '    c = (pid*BLOCK+tl.arange(0, BLOCK)).to(tl.int64)',
         '    m = c < ncell',
         '    x0 = c % cx',
         '    y0 = (c//cx) % cy',
         '    z0 = c//(cx*cy)',
         '    base = (z0*ny+y0)*nx+x0',
         '    s = ny*nx',
         '    ih0 = tl.load(k_ptr+0)',
         '    ih1 = tl.load(k_ptr+1)',
         '    ih2 = tl.load(k_ptr+2)',
         '    delta = tl.load(k_ptr+3)',
         '    L1 = tl.load(k_ptr+4)',
         '    L2 = tl.load(k_ptr+5)',
         '    L3 = tl.load(k_ptr+6)',
         '    inf = float("inf")',
         '    best = tl.full((BLOCK,), inf, tl.float64)',
         '    invalid = tl.zeros((BLOCK,), tl.int32)',
         '    bad = tl.zeros((BLOCK,), tl.int32)']
    offsets = {a: f'base+{(a >> 2) & 1}*s+{(a >> 1) & 1}*nx+{a & 1}' for a in range(8)}
    for name in ('u', 'v'):
        for a in range(8):
            for r in range(3):
                L.append(f'    {name}{a}_{r} = tl.load({name}_ptr+({offsets[a]})*3+{r}, mask=m, other=0.)')
    for name in ('u', 'v'):
        for j in range(3):
            for e, (a, b) in enumerate(EDGES[j]):
                for r in range(3):
                    L.append(f'    {name}e{j}{e}{r} = ({name}{b}_{r}-{name}{a}_{r})*ih{j}')
    for iz, iy, ix in product(range(3), repeat=3):
        point = (ix/2, iy/2, iz/2)
        p = 9*iz+3*iy+ix
        L.append(f'    # point {p}: (x, y, z) = {point}')
        for name, ident in (('F', True), ('V', False)):
            src = 'u' if name == 'F' else 'v'
            for r in range(3):
                for j in range(3):
                    terms = []
                    for e, (a, b) in enumerate(EDGES[j]):
                        w = weight(a, j, point)
                        if w == 0.:
                            continue
                        terms.append(f'{src}e{j}{e}{r}' if w == 1. else f'{w!r}*{src}e{j}{e}{r}')
                    expr = '+'.join(terms) if terms else '0.'
                    if ident and r == j:
                        expr = f'1.+({expr})'
                    L.append(f'    {name}{r}{j} = {expr}')
        # cofactor rows (cyclic cross products), both F and V
        for name in ('F', 'V'):
            for r, (j, k) in ((0, (1, 2)), (1, (2, 0)), (2, (0, 1))):
                for cidx, (l, mm) in ((0, (1, 2)), (1, (2, 0)), (2, (0, 1))):
                    L.append(f'    A{name}{r}{cidx} = {name}{j}{l}*{name}{k}{mm}-{name}{j}{mm}*{name}{k}{l}')
        L.append('    c0 = (F00*AF00+F01*AF01+F02*AF02)-delta')
        L.append('    b1 = (' + '+'.join(f'AF{r}{j}*V{r}{j}' for r in range(3) for j in range(3)) + ')*L1')
        L.append('    b2 = (' + '+'.join(f'F{r}{j}*AV{r}{j}' for r in range(3) for j in range(3)) + ')*L2')
        L.append('    b3 = (V00*AV00+V01*AV01+V02*AV02)*L3')
        L.append('    fin = (c0 == c0) & (b1 == b1) & (b2 == b2) & (b3 == b3) & (tl.abs(c0) < inf) & (tl.abs(b1) < inf) '
                 '& (tl.abs(b2) < inf) & (tl.abs(b3) < inf)')
        L.append('    bad = tl.where(m & ~fin, 1, bad)')
        L.append('    valid = m & fin & (c0 > 0)')
        L.append('    invalid += tl.where(m & fin & ~(c0 > 0), 1, 0)')
        L.append('    best = tl.minimum(best, _first_root(tl.where(valid, c0, 1.), b1, b2, b3, valid))')
    L += ['    tl.store(min_ptr+pid, tl.min(best, axis=0))',
          '    tl.store(inv_ptr+pid, tl.sum(invalid, axis=0))',
          '    tl.store(bad_ptr+pid, tl.max(bad, axis=0))', '']
    return L


if __name__ == '__main__':
    OUT.write_text('\n'.join(lines()))
    print(OUT, len(lines()))

"""Generate jd_curl/three_d/backends/triton_node_jd_kernels.py (E94 / G2-C4, fused T62/T69 cell measure).

One cell per lane, reproducing TorchLinearization.node_min_closed27_jd's per-cell values bit for bit (the
kernel is launched with enable_fp_fusion=False, so only the explicit tl.fma calls below are fused):
- V[r][j] at each closed27 point = the einsum 'jpa,tar->tprj' with the closed27 table D: a sequential FMA chain
  over the vertices a = 0..7 in increasing order (cuBLAS, measured; results/verification/3d_stage_E94_v1/analysis),
  starting with the rounded product; D[j,p,a] = +-w*fl(1/h_j) with w in {1/4, 1/2, 1} exactly; zero terms are
  skipped (they can only change the sign of an exact zero, which F = V + I turns into +0);
- F = V + I (diagonal + 1.0, off-diagonal + 0.0); row 0 of the cofactor = torch.linalg.cross(F1, F2) on CUDA,
  i.e. fma(a1, b1, -(a2*b2)) with a true negation; J = ((P0 + P2) + P1) + 0 with P_k = F0k*row0_k (torch's sum
  over the last axis of 3, whose accumulators start from +0);
- every minimum propagates NaN like torch.minimum / min / clamp;
- the 12 edge quadratics exactly as the torch expressions (a = 2*((f0 - 2*f1) + f2), b = ((-3*f0) + 4*f1) - f2,
  vertex = f0 - (b*b)/(4*a) where an interior minimum exists), minima = min(min J, min vertex);
- with EXT: the Bernstein coefficients beta = J @ M (cuBLAS, K = 27: a sequential FMA chain over p in increasing
  order, measured; zero entries skipped as above), candidate = min beta < min(minima, activation).
Per cell: minima (float64), candidate flag (int8), nonfinite flag (int8, any J nonfinite: the caller runs the
torch path instead). Usage: python scripts/gen_triton_node_jd.py
"""
from itertools import product
from pathlib import Path
import sys

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
OUT = ROOT/'jd_curl/three_d/backends/triton_node_jd_kernels.py'


def edge_indices():
    from jd_curl.three_d.solvers.jd_affine import EDGE_INDICES
    return np.asarray(EDGE_INDICES)


def bernstein_columns():
    """M = TB.T (beta = J @ M): for each k, the nonzero (p, value) pairs in increasing p."""
    from jd_curl.three_d.bernstein_barrier import TB
    M = np.asarray(TB, dtype=np.float64).T
    return [[(p, float(M[p, k])) for p in range(27) if M[p, k] != 0.] for k in range(27)]


def coefficient(a, j, point):
    """(sign, w) of D[j, p, a] = sign*w*fl(1/h_j) for vertex a = 4z+2y+x at a reference point (x, y, z)."""
    bits = (a & 1, (a >> 1) & 1, (a >> 2) & 1)
    w = 1.
    for k in range(3):
        if k != j:
            w *= point[k] if bits[k] else 1-point[k]
    return (1. if bits[j] else -1.), w


def cell_j27_lines(ind):
    """The 27 closed27 values J0..J26 of the cell at node `base` (needs u_ptr, s, nx, m, ih0..2, inf, fin)."""
    L = []
    offsets = {a: f'base+{(a >> 2) & 1}*s+{(a >> 1) & 1}*nx+{a & 1}' for a in range(8)}
    for a in range(8):
        for r in range(3):
            L.append(f'{ind}u{a}_{r} = tl.load(u_ptr+({offsets[a]})*3+{r}, mask=m, other=0.)')
    # exact coefficients d = sign*w*ih_j (w a power of two: exact)
    coeffs = {}
    for j in range(3):
        for sign in (-1., 1.):
            for w in (.25, .5, 1.):
                name = f'd{j}_{"m" if sign < 0 else "p"}{str(w).replace(".", "")}'
                coeffs[(j, sign, w)] = name
                L.append(f'{ind}{name} = ({sign*w!r})*ih{j}')
    for iz, iy, ix in product(range(3), repeat=3):
        point = (ix/2, iy/2, iz/2)
        p = 9*iz+3*iy+ix
        L.append(f'{ind}# point {p}: (x, y, z) = {point}')
        for r in range(3):
            for j in range(3):
                terms = []
                for a in range(8):
                    sign, w = coefficient(a, j, point)
                    if w != 0.:
                        terms.append((coeffs[(j, sign, w)], f'u{a}_{r}'))
                expr = f'{terms[0][0]}*{terms[0][1]}'
                for d, x in terms[1:]:
                    expr = f'tl.fma({d}, {x}, {expr})'
                L.append(f'{ind}V{r}{j} = {expr}')
                L.append(f'{ind}F{r}{j} = V{r}{j}+{1. if r == j else 0.!r}')
        # true negation (-1.0*x keeps the sign of zero; Triton's unary minus is 0 - x)
        L.append(f'{ind}A0 = tl.fma(F11, F22, (-1.0)*(F12*F21))')
        L.append(f'{ind}A1 = tl.fma(F12, F20, (-1.0)*(F10*F22))')
        L.append(f'{ind}A2 = tl.fma(F10, F21, (-1.0)*(F11*F20))')
        # torch's length-3 reduction starts from +0: an all -0 sum is +0 there
        L.append(f'{ind}J{p} = ((F00*A0+F02*A2)+F01*A1)+0.0')
        L.append(f'{ind}fin = fin & (J{p} == J{p}) & (tl.abs(J{p}) < inf)')
    return L


def lines():
    L = ['"""GENERATED by scripts/gen_triton_node_jd.py (E94). Do not edit by hand.',
         '',
         'k[0:3] = fl(1/hx), fl(1/hy), fl(1/hz); k[3] = T69 activation (used only with EXT). Launch with enable_fp_fusion=False.',
         '"""',
         'import triton',
         'import triton.language as tl',
         '',
         '# the tables this kernel was generated from (checked against the live ones before use)',
         f'EDGES = {[[int(x) for x in e] for e in edge_indices()]!r}',
         f'M_COLUMNS = {bernstein_columns()!r}',
         '',
         '',
         '@triton.jit(do_not_specialize=["ncell", "ny", "nx", "cy", "cx"])',
         'def node_jd_kernel(u_ptr, k_ptr, minima_ptr, cand_ptr, bad_ptr, ncell, ny, nx, cy, cx,',
         '                   EXT: tl.constexpr, BLOCK: tl.constexpr):',
         '    pid = tl.program_id(0)',
         '    c = (pid*BLOCK+tl.arange(0, BLOCK)).to(tl.int64)',
         '    m = c < ncell',
         '    x0 = c % cx',
         '    y0 = (c//cx) % cy',
         '    z0 = c//(cx*cy)',
         '    base = (z0*ny+y0)*nx+x0',
         '    s = ny*nx',
         '    ih0 = tl.load(k_ptr+0)',
         '    ih1 = tl.load(k_ptr+1)',
         '    ih2 = tl.load(k_ptr+2)',
         '    act = tl.load(k_ptr+3)',
         '    inf = float("inf")',
         '    fin = m']
    L += cell_j27_lines('    ')
    # minima over the 27 values and the 12 edge vertices
    L.append('    jmin = J0')
    for p in range(1, 27):
        L.append(f'    jmin = tl.minimum(jmin, J{p}, propagate_nan=tl.PropagateNan.ALL)')
    L.append('    vmin = tl.full((BLOCK,), inf, tl.float64)')
    for e, (i0, i1, i2) in enumerate(edge_indices()):
        L.append(f'    # edge {e}: points {i0}, {i1}, {i2}')
        L.append(f'    ea = 2.*((J{i0}-2.*J{i1})+J{i2})')
        L.append(f'    eb = ((-3.)*J{i0}+4.*J{i1})-J{i2}')
        L.append('    inside = (ea > 0) & (eb < 0) & (-eb < 2.*ea)')
        L.append(f'    vertex = tl.where(inside, J{i0}-(eb*eb)/(4.*tl.where(inside, ea, 1.)), inf)')
        L.append('    vmin = tl.minimum(vmin, vertex, propagate_nan=tl.PropagateNan.ALL)')
    L.append('    minima = tl.minimum(jmin, vmin, propagate_nan=tl.PropagateNan.ALL)')
    L.append('    tl.store(minima_ptr+c, minima, mask=m)')
    L.append('    tl.store(bad_ptr+c, tl.where(fin, 0, 1).to(tl.int8), mask=m)')
    L.append('    if EXT:')
    L.append('        bmin = tl.full((BLOCK,), inf, tl.float64)')
    for k, column in enumerate(bernstein_columns()):
        (p0, v0), rest = column[0], column[1:]
        expr = f'J{p0}*({v0!r})'
        for p, v in rest:
            expr = f'tl.fma(J{p}, {v!r}, {expr})'
        L.append(f'        bmin = tl.minimum(bmin, {expr}, propagate_nan=tl.PropagateNan.ALL)')
    L.append('        cand = bmin < tl.minimum(minima, act, propagate_nan=tl.PropagateNan.ALL)')
    L.append('        tl.store(cand_ptr+c, tl.where(cand, 1, 0).to(tl.int8), mask=m)')
    # the 27 values of listed cells (candidates), the same code as above
    L += ['',
          '',
          '@triton.jit(do_not_specialize=["n", "ny", "nx", "cy", "cx"])',
          'def cell_j27_kernel(u_ptr, k_ptr, cells_ptr, out_ptr, n, ny, nx, cy, cx, BLOCK: tl.constexpr):',
          '    pid = tl.program_id(0)',
          '    i = (pid*BLOCK+tl.arange(0, BLOCK)).to(tl.int64)',
          '    m = i < n',
          '    c = tl.load(cells_ptr+i, mask=m, other=0)',
          '    x0 = c % cx',
          '    y0 = (c//cx) % cy',
          '    z0 = c//(cx*cy)',
          '    base = (z0*ny+y0)*nx+x0',
          '    s = ny*nx',
          '    ih0 = tl.load(k_ptr+0)',
          '    ih1 = tl.load(k_ptr+1)',
          '    ih2 = tl.load(k_ptr+2)',
          '    inf = float("inf")',
          '    fin = m']
    L += cell_j27_lines('    ')
    for p in range(27):
        L.append(f'    tl.store(out_ptr+i*27+{p}, J{p}, mask=m)')
    L.append('')
    return L


def check_literals(text):
    """Triton 3.1 rounds Python float literals in the fp32 range to fp32 first: every literal must be fp32-exact."""
    import re
    for token in set(re.findall(r'(?<![\w.])-?(?:\d+\.\d*|\.\d+|\d+(?=[eE]))(?:[eE][-+]?\d+)?', text)):
        v = float(token)
        if float(np.float32(v)) != v:
            raise ValueError('literal not exact in fp32: '+token)


def main():
    text = '\n'.join(lines())
    check_literals(text)
    OUT.write_text(text)
    print(OUT)


if __name__ == '__main__':
    main()

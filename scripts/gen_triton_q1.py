         '    """Per-cell Gauss JD/curl change-penalty gradient contributions (T08 VJP)."""',
         *(['    j = tl.program_id(0)*BLOCK+tl.arange(0, BLOCK)', '    mj = j < nidx',
         '    c = tl.load(idx_ptr+j, mask=mj, other=ncell).to(tl.int64)', '    m = mj & (c < ncell)',] if indexed else ['    c = (tl.program_id(0)*BLOCK+tl.arange(0, BLOCK)).to(tl.int64)', '    m = c < ncell',]),

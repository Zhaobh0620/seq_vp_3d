# E98 (C2, throughput-v16): the barrier energy and gradient kernels with the helper skipped at inactive closed27
# points. At a point where every active lane has J >= act (and, for the change, Ja >= act), each helper returns an
# exact signed zero. The energies skip the helper and its accumulation inside one branch, in the original statement
# order (the accumulators start at +0 and are never -0 in round-to-nearest, so adding a zero keeps their bits). The
# gradient skips only the helper (its value is then +0 instead of +-0); the products with cofactors and basis
# gradients and the accumulations stay outside the branch, exactly as in the original straight-line code, so the
# compiler forms the same operations (a first version that also branched the accumulations gave rounding-level
# differences: contraction differs). A per-cell guard on the loaded vertex values (|u| <= 1e100; with 1/h <= 1e30
# every edge is at most 2e130 and every cofactor finite) keeps those products finite for the +0; it reads the
# vertices, not the edges, so that the edge products keep their single use and the compiler contracts them as in
# the original (a guard on the edges changed nine contractions at the first point). NaN J counts as active (ordered
# >=). The v15 kernels above are unchanged; the host compares each kernel with them on every grid until a call in
# which the active branch ran matches bit for bit. A GGN-diagonal variant was dropped (about 4% faster, not
# bit-identical on an L2 state).
VERTEX_NAMES = [f"u{a}_{r}" for a in range(8) for r in range(3)]


def _vertex_guard(L):
    L.append("    ok = " + " & ".join(f"(tl.abs({n}) <= 1e100)" for n in VERTEX_NAMES))



"""Generate jd_curl/three_d/backends/triton_q1_kernels.py (E51/S3 fused Q1 kernels).

The generated file is checked in; regenerate with
    python scripts/gen_triton_q1.py
Every statement is an explicit unrolled float64 expression of the Q1
edge-difference/bilinear form (T02) at 27 points; see triton_q1.py for the
contract and the independent tests in tests/three_d/test_triton_q1_e51.py.
"""
from itertools import product
from pathlib import Path

OUT = Path(__file__).resolve().parents[1]/'jd_curl/three_d/backends/triton_q1_kernels.py'
OUT_IDX = Path(__file__).resolve().parents[1]/'jd_curl/three_d/backends/triton_q1_idx_kernels.py'   # T89 (S30-G4)
OUT_F32 = Path(__file__).resolve().parents[1]/'jd_curl/three_d/backends/triton_q1_f32_kernels.py'   # T90 (S30-G5)
F32 = '.to(tl.float32)'
OTHER = {0: (1, 2), 1: (0, 2), 2: (0, 1)}
AX = 'xyz'


def bit(a, axis):
    return (a >> axis) & 1


def edge_vertices(j, k):
    """Vertex pair (a0,a1) of the j-direction edge with other-axis bits k=(b_o1,b_o2)."""
    o1, o2 = OTHER[j]
    a0 = (k[0] << o1) | (k[1] << o2)
    return a0, a0 | (1 << j)


def factor(b, s):
    return f"{s}" if b else f"(1.-{s})"


def load_vertices(lines, name, ptr, comps=(0, 1, 2), cast=''):
    for a in range(8):
        for r in comps:
            lines.append(f"    {name}{a}_{r} = tl.load({ptr}+n{a}*3+{r}, mask=m, other=0.){cast}")


def edges(lines, name, vname):
    for j in range(3):
        for r in range(3):
            for k in product((0, 1), repeat=2):
                a0, a1 = edge_vertices(j, k)
                lines.append(f"    {name}{j}{r}{k[0]}{k[1]} = ({vname}{a1}_{r}-{vname}{a0}_{r})*ih{AX[j]}")


def point_V(lines, out, ename, s):
    """V[r][j] = sum_k e[j][r][k] * f(k0, s_o1) f(k1, s_o2) at point s=(sx,sy,sz) names."""
    for r in range(3):
        for j in range(3):
            o1, o2 = OTHER[j]
            terms = []
            for k in product((0, 1), repeat=2):
                terms.append(f"{ename}{j}{r}{k[0]}{k[1]}*{factor(k[0], s[o1])}*{factor(k[1], s[o2])}")
            lines.append(f"    {out}{r}{j} = ({terms[0]}+{terms[1]})+({terms[2]}+{terms[3]})")


def geometry(lines, V, J, A=None, C=None):
    """F = I + V; row0 cofactor = cross(F1,F2); J = F0.A0 (legacy order). Optional rows 1,2 and curl."""
    F = lambda r, j: f"({V}{r}{j}+1.)" if r == j else f"{V}{r}{j}"
    a00 = f"({F(1,1)}*{F(2,2)}-{F(1,2)}*{F(2,1)})"
    a01 = f"({F(1,2)}*{F(2,0)}-{F(1,0)}*{F(2,2)})"
    a02 = f"({F(1,0)}*{F(2,1)}-{F(1,1)}*{F(2,0)})"
    if A is not None:
        lines.append(f"    {A}00 = {a00}"); lines.append(f"    {A}01 = {a01}"); lines.append(f"    {A}02 = {a02}")
        lines.append(f"    {A}10 = ({F(2,1)}*{F(0,2)}-{F(2,2)}*{F(0,1)})")
        lines.append(f"    {A}11 = ({F(2,2)}*{F(0,0)}-{F(2,0)}*{F(0,2)})")
        lines.append(f"    {A}12 = ({F(2,0)}*{F(0,1)}-{F(2,1)}*{F(0,0)})")
        lines.append(f"    {A}20 = ({F(0,1)}*{F(1,2)}-{F(0,2)}*{F(1,1)})")
        lines.append(f"    {A}21 = ({F(0,2)}*{F(1,0)}-{F(0,0)}*{F(1,2)})")
        lines.append(f"    {A}22 = ({F(0,0)}*{F(1,1)}-{F(0,1)}*{F(1,0)})")
        lines.append(f"    {J} = ({F(0,0)}*{A}00+{F(0,1)}*{A}01)+{F(0,2)}*{A}02")
    else:
        lines.append(f"    {J} = ({F(0,0)}*{a00}+{F(0,1)}*{a01})+{F(0,2)}*{a02}")
    if C is not None:
        lines.append(f"    {C}0 = {V}21-{V}12"); lines.append(f"    {C}1 = {V}02-{V}20"); lines.append(f"    {C}2 = {V}10-{V}01")


def accumulate_transpose(lines, G, flux, s):
    """G[j][r][k] += f(k0,s_o1) f(k1,s_o2) * flux[r][j]."""
    for j in range(3):
        o1, o2 = OTHER[j]
        for r in range(3):
            for k in product((0, 1), repeat=2):
                lines.append(f"    {G}{j}{r}{k[0]}{k[1]} += {factor(k[0], s[o1])}*{factor(k[1], s[o2])}*{flux}{r}{j}")


def store_locals(lines, G, out_ptr):
    """local[a][r] = sum_j (+/- ih_j) G[j][r][k(a)]; stored at out[cell*24 + a*3 + r]."""
    for a in range(8):
        for r in range(3):
            terms = []
            for j in range(3):
                o1, o2 = OTHER[j]
                k = (bit(a, o1), bit(a, o2))
                terms.append(('+' if bit(a, j) else '-', f"ih{AX[j]}*{G}{j}{r}{k[0]}{k[1]}"))
            expr = terms[0][1] if terms[0][0] == '+' else f"(-{terms[0][1]})"
            for sign, t in terms[1:]:
                expr = f"({expr}{sign}{t})"
            lines.append(f"    tl.store({out_ptr}+c*24+{a*3+r}, {expr}, mask=m)")


HEADER = '''"""GENERATED by scripts/gen_triton_q1.py (E51/S3). Do not edit by hand.

Unrolled float64 Q1 kernels. Constants come from the float64 tensor `k`:
k[0:3]=1/hx,1/hy,1/hz; k[3:6]=Gauss nodes; k[6:33]=Gauss weights qw (omega*w_i w_j w_k,
point order z,y,x with x fastest); k[33]=mu; k[34]=nu; k[35]=barrier weight;
k[36]=delta; k[37]=activation; k[38]=activation-delta.
"""
import triton
import triton.language as tl
from triton.language.extra import libdevice


@triton.jit
def _nodes(c, ny, nx, cy, cx):
    x0 = c % cx
    y0 = (c//cx) % cy
    z0 = c//(cx*cy)
    b = (z0*ny+y0)*nx+x0
    s = ny*nx
    return b, b+1, b+nx, b+nx+1, b+s, b+s+1, b+s+nx, b+s+nx+1


@triton.jit
def _barrier_first(J, w, delta, act, scale):
    r = tl.maximum(act-J, 0.)/scale
    t = (tl.minimum(J, act)-delta)/scale
    logt = tl.where(r < .5, libdevice.log1p(-r), libdevice.log(t))
    return w*(2.*r*logt-r*r/t)/scale


@triton.jit
def _barrier_value(J, w, delta, act, scale):
    r = tl.maximum(act-J, 0.)/scale
    t = (tl.minimum(J, act)-delta)/scale
    logt = tl.where(r < .5, libdevice.log1p(-r), libdevice.log(t))
    return -w*r*r*logt


@triton.jit
def _barrier_change(Ja, Jb, delta, act, scale):
    a = tl.minimum(Ja, act)
    b = tl.minimum(Jb, act)
    ra = (act-a)/scale
    rb = (act-b)/scale
    h = (b-a)/scale
    loga = tl.where(ra < .5, libdevice.log1p(-ra), libdevice.log((a-delta)/scale))
    x = (b-a)/(a-delta)
    logratio = tl.where(x >= -.5, libdevice.log1p(x), libdevice.log((b-delta)/(a-delta)))
    return h*(ra+rb)*loga-rb*rb*logratio
'''


def gauss_points():
    return [(px, py, pz) for pz in range(3) for py in range(3) for px in range(3)]



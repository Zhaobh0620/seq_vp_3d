def kernel_ggn_diag(indexed=False):
    """E65: exact diagonal of the frozen full GGN restricted to the geometry and barrier blocks.
    GG2 (indexed=True): the index-list variant ggn_diag_idx_kernel (cells idx_ptr[j], j < nidx), same per-cell arithmetic
    and the same per-cell store into the full-size locals buffer; the reference text (indexed=False) is unchanged.

    Per cell, vertex a and component r (T09 GGN; samples barrier basis only):
      sum_{Gauss p} qw_p (mu (A_p[r,:] . dN_a(p))^2 + nu sum_{j != r} dN_a,j(p)^2)
      + sum_{closed27 p} psi''(J_p) (A_p[r,:] . dN_a(p))^2,
    with A the cofactor of F = I + grad u and dN_a the Q1 physical basis gradient; the node
    term q (b^2 + lambda) is added by the gather base (same as torch_ops.diagonal).
    """
    L = ['', '', '@triton.jit',
         'def _barrier_second(J, w, delta, act, scale):',
         '    r = tl.maximum(act-J, 0.)/scale',
         '    t = (tl.minimum(J, act)-delta)/scale',
         '    logt = tl.where(r < .5, libdevice.log1p(-r), libdevice.log(t))',
         '    q = r/t',
         '    return w*(-2.*logt+4.*q+q*q)/(scale*scale)',
         '', '',
         ('@triton.jit(do_not_specialize=["nidx", "ncell", "ny", "nx", "cy", "cx"])' if indexed else
          '@triton.jit(do_not_specialize=["ncell", "ny", "nx", "cy", "cx"])'),
         ('def ggn_diag_idx_kernel(u_ptr, k_ptr, out_ptr, idx_ptr, nidx, ncell, ny, nx, cy, cx, BLOCK: tl.constexpr):' if indexed else
          'def ggn_diag_kernel(u_ptr, k_ptr, out_ptr, ncell, ny, nx, cy, cx, BLOCK: tl.constexpr):'),
         '    """Per-cell (8 vertices x 3 components) GGN diagonal contributions (soft + closed27 barrier)."""',
         *(['    j = tl.program_id(0)*BLOCK+tl.arange(0, BLOCK)', '    mj = j < nidx',
            '    c = tl.load(idx_ptr+j, mask=mj, other=ncell).to(tl.int64)', '    m = mj & (c < ncell)'] if indexed else
           ['    c = (tl.program_id(0)*BLOCK+tl.arange(0, BLOCK)).to(tl.int64)', '    m = c < ncell']),
         '    n0, n1, n2, n3, n4, n5, n6, n7 = _nodes(c, ny, nx, cy, cx)',
         '    ihx = tl.load(k_ptr+0); ihy = tl.load(k_ptr+1); ihz = tl.load(k_ptr+2)',
         '    g0 = tl.load(k_ptr+3); g1 = tl.load(k_ptr+4); g2 = tl.load(k_ptr+5)',
         '    mu = tl.load(k_ptr+33); nu = tl.load(k_ptr+34)',
         '    w = tl.load(k_ptr+35); delta = tl.load(k_ptr+36); act = tl.load(k_ptr+37); scale = tl.load(k_ptr+38)']
    load_vertices(L, 'u', 'u_ptr'); edges(L, 'e', 'u')
    for a in range(8):
        for r in range(3):
            L.append(f"    D{a}_{r} = tl.zeros([BLOCK], dtype=tl.float64)")

    def basis_gradients(s):
        for a in range(8):
            for j in range(3):
                o1, o2 = OTHER[j]
                sign = '' if bit(a, j) else '-'
                L.append(f"    d{a}{j} = {sign}ih{AX[j]}*{factor(bit(a, o1), s[o1])}*{factor(bit(a, o2), s[o2])}")
    g = ('g0', 'g1', 'g2')
    for p, (px, py, pz) in enumerate(gauss_points()):
        s = (g[px], g[py], g[pz])
        L.append(f"    qw = tl.load(k_ptr+{6+p})")
        point_V(L, 'V', 'e', s); geometry(L, 'V', 'J', A='A')
        basis_gradients(s)
        for a in range(8):
            for r in range(3):
                lj = f"(A{r}0*d{a}0+A{r}1*d{a}1)+A{r}2*d{a}2"
                cs = '+'.join(f"d{a}{j}*d{a}{j}" for j in range(3) if j != r)
                L.append(f"    l = {lj}")
                L.append(f"    D{a}_{r} += qw*(mu*(l*l)+nu*({cs}))")
    cl = ('0.', '.5', '1.')
    for (px, py, pz) in gauss_points():
        s = (cl[px], cl[py], cl[pz])
        point_V(L, 'V', 'e', s); geometry(L, 'V', 'J', A='A')
        L.append("    b2 = tl.where(m, _barrier_second(tl.where(m, J, 1.), w, delta, act, scale), 0.)")
        basis_gradients(s)
        for a in range(8):
            for r in range(3):
                L.append(f"    l = (A{r}0*d{a}0+A{r}1*d{a}1)+A{r}2*d{a}2")
                L.append(f"    D{a}_{r} += b2*(l*l)")
    for a in range(8):
        for r in range(3):
            L.append(f"    tl.store(out_ptr+c*24+{a*3+r}, D{a}_{r}, mask=m)")
    return L



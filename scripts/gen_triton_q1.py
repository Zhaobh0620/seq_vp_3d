def bernstein_forward(lines, src, dst):
    """E58/T68: dst{k} = (T x T x T) src{p}, T = [[1,0,0],[-.5,2,-.5],[0,0,1]], along x, y, z in turn.

    Index 9*iz+3*iy+ix; middle entries 2*b - .5*(a+c) (same operations as lagrange_to_bernstein).
    """
    cur = {p: f"{src}{p}" for p in range(27)}
    for stride in (1, 3, 9):
        nxt = {}
        for p in range(27):
            i = (p//stride) % 3
            base = p-i*stride
            if i == 1:
                name = f"{dst}s{stride}_{p}"
                lines.append(f"    {name} = 2.*{cur[p]}-.5*({cur[base]}+{cur[base+2*stride]})")
                nxt[p] = name
            else:
                nxt[p] = cur[p]
        cur = nxt
    for p in range(27):
        lines.append(f"    {dst}{p} = {cur[p]}")


def bernstein_transpose(lines, src, dst):
    """E58/T68: dst{p} = sum_k TB[k,p] src{k}; per axis T^T = [[1,-.5,0],[0,2,0],[0,-.5,1]]."""
    cur = {k: f"{src}{k}" for k in range(27)}
    for stride in (1, 3, 9):
        nxt = {}
        for p in range(27):
            i = (p//stride) % 3
            base = p-i*stride
            d0, d1, d2 = cur[base], cur[base+stride], cur[base+2*stride]
            name = f"{dst}t{stride}_{p}"
            lines.append(f"    {name} = " + {0: f"{d0}-.5*{d1}", 1: f"2.*{d1}", 2: f"{d2}-.5*{d1}"}[i])
            nxt[p] = name
        cur = nxt
    for p in range(27):
        lines.append(f"    {dst}{p} = {cur[p]}")


